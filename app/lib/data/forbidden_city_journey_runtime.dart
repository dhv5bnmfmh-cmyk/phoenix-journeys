List<String> validateForbiddenCityWordTrace() {
  final invalid = <String>[];
  for (final record in forbiddenCityWordRecords) {
    final word = record.entry.word;
    final source = record.storySource;
    final containingLevels = <int>[];
    for (var index = 0; index < forbiddenCityLockedStories.length; index++) {
      if (forbiddenCityLockedStories[index].contains(word)) {
        containingLevels.add(index + 1);
      }
    }
    if (containingLevels.isEmpty ||
        !forbiddenCityLockedStories.any((story) => story.contains(source)) ||
        !source.contains(word) ||
        containingLevels.first != record.firstAppearsAt) {
      invalid.add(word);
    }
  }
  return invalid;
}

List<WordEntry> forbiddenCityWordsForLevel(int level) {
  final story = forbiddenCityLockedStories[level.clamp(1, 10) - 1];
  final candidates = forbiddenCityWordRecords
      .where((record) =>
          record.firstAppearsAt <= level && story.contains(record.entry.word))
      .map((record) => record.entry)
      .toList(growable: false);
  final target = (5 + level).clamp(6, 15);
  return candidates.take(target).toList(growable: false);
}

List<String> forbiddenCityStoryReadingSegments(String story, int level) {
  final blocks = story.split('\n\n').where((block) => block.isNotEmpty).toList(growable: false);
  if (blocks.length <= 1) return blocks;

  final safeLevel = level.clamp(1, 10);
  final targetCharacters = (180 + safeLevel * 20).clamp(200, 380);
  final minimumBeforeBreak = (targetCharacters * .58).round();
  final segments = <String>[];
  var current = '';

  for (final block in blocks) {
    if (current.isEmpty) {
      current = block;
      continue;
    }
    final candidate = '$current\n\n$block';
    if (current.length >= minimumBeforeBreak && candidate.length > targetCharacters) {
      segments.add(current);
      current = block;
    } else {
      current = candidate;
    }
  }
  if (current.isNotEmpty) segments.add(current);
  return segments;
}

