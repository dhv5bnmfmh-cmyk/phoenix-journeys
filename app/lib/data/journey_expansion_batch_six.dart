JourneyContentRecord _record(
  String id,
  String title,
  String geoNodeId,
  String sourceId,
  List<String> paragraphs,
  List<String> tags,
) {
  return JourneyContentRecord(
    id: id,
    title: title,
    geoNodeId: geoNodeId,
    languageCode: 'zh-CN',
    verificationStatus: StoryVerificationStatus.published,
    tags: tags,
    sections: List.generate(
      paragraphs.length,
      (index) => JourneyStorySection(
        id: 'story-$index',
        text: paragraphs[index],
        sourceIds: [sourceId],
      ),
    ),
  );
}

